HEIGHT = 12
SPACE = 3
GAP = 1


def glyph(ch):
    rows = GLYPHS[ch]
    w = max(len(r) for r in rows)
    return [r.ljust(w, ".") for r in rows] + ["." * w] * (HEIGHT - len(rows))


def text_width(text):
    w = 0
    for i, ch in enumerate(text):
        w += SPACE if ch == " " else len(glyph(ch)[0])
        if i < len(text) - 1:
            w += GAP
    return w


def draw_text(mask, text, x, y):
    """Dibuja el texto (1 = letra) en una imagen modo "1" a partir de (x, y)."""
    for ch in text:
        if ch == " ":
            x += SPACE + GAP
            continue
        rows = glyph(ch)
        for dy, row in enumerate(rows):
            for dx, c in enumerate(row):
                if c == "#":
                    mask.putpixel((x + dx, y + dy), 1)
        x += len(rows[0]) + GAP


def credit_image(background, lines, white, black):
    """Compone líneas de texto centradas sobre un recorte del fondo (modo "P").

    lines: [(texto, fila superior)]. Letras blancas con contorno negro de 1 px."""
    w, h = background.size
    mask = Image.new("1", (w, h), 0)
    for text, top in lines:
        tw = text_width(text)
        assert tw <= w - 2, (text, tw, w)
        draw_text(mask, text, (w - tw) // 2, top)
    edge = mask.filter(ImageFilter.MaxFilter(3))
    out = background.copy()
    out.paste(black, mask=edge)
    out.paste(white, mask=mask)
    return out
